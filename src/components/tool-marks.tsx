export function ToolMark({ tool, size = 14, uid = "0" }: { tool: string; size?: number; uid?: string }) {
  const supplied = SUPPLIED[tool];
  if (supplied) {
    return (
      <svg
        className="chip-mark"
        width={size}
        height={size}
        viewBox={supplied.viewBox}
        aria-hidden="true"
        focusable="false"
      >
        {supplied.render(uid)}
      </svg>
    );
  }
  const key = FOR_TOOL[tool];
  const d = key ? PATHS[key] : undefined;
  if (!d) {
    const glyph = GLYPHS[tool];
    if (!glyph) return null;
    return (
      <svg
        className="chip-mark"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={1.7}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
      >
        {glyph}
      </svg>
    );
  }
  return (
    <svg
      className="chip-mark"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={COLOURS[key] ?? "currentColor"}
      aria-hidden="true"
      focusable="false"
    >
      <path d={d} />
    </svg>
  );
}
